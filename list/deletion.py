# `remove()`
# * `pop()`
# * `del`
# * `clear()`

# pop remove element from the last index of the list
list=["Ashu","alok","aryan","avinash"]
list.pop()
print(list)

# remove to delete using specific index or name
list.remove("Ashu")
print(list)

# del it  delete iteam using index value
del list[0]

# clear for remove all element from our list
list.clear()
print(list)
